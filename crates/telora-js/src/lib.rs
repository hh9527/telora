//! Experimental direct JavaScript emission from sealed frontend evidence.
use std::collections::BTreeSet;
use telora_core::mir::*;
use telora_core::syntax::kinds::{BinaryOperator as B, BindingKind, UnaryOperator as U};

/// Emit a standalone ES module exporting the selected value as `default`.
/// Unsupported constructs fail compilation rather than falling back to Wasm.
pub fn compile_executable(executable: &SealedExecutable<'_>) -> Result<String, String> {
    if !executable.instances().is_empty() || !executable.checks().is_empty() {
        return Err(
            "JS prototype: generic instances and construction checks are unsupported".into(),
        );
    }
    let mir = executable.sealed_mir().mir();
    let mut emit = Emit {
        mir,
        globals: BTreeSet::new(),
        locals: BTreeSet::new(),
        pending: vec![],
    };
    let entry = emit.expr(executable.root())?;
    let mut definitions = String::new();
    while let Some(symbol) = emit.pending.pop() {
        let node = *mir.symbols[symbol.index()]
            .declarations
            .last()
            .ok_or("JS: missing declaration")?;
        let value = emit.expr(node)?;
        definitions.push_str(&format!(
            "const g{} = memo(() => {value});\n",
            symbol.index()
        ));
    }
    Ok(format!(
        "{RUNTIME}\n{definitions}\nexport default {entry};\n"
    ))
}

const RUNTIME: &str = r#"// Generated by the experimental Telora JS backend
const i64 = x => {
  if (x < -9223372036854775808n || x > 9223372036854775807n)
    throw new RangeError('Telora Int overflow');
  return x;
};
const memo = f => {
  let state = 0, value;
  return () => {
    if (state === 2) return value;
    if (state === 1) throw new Error('Telora cyclic initialization');
    state = 1;
    try { value = f(); state = 2; return value; }
    catch (error) { state = 0; throw error; }
  };
};
"#;

struct Emit<'a> {
    mir: &'a Mir,
    globals: BTreeSet<SymbolId>,
    pending: Vec<SymbolId>,
    locals: BTreeSet<SymbolId>,
}
impl Emit<'_> {
    fn child(&self, node: HirId, role: Role) -> Result<HirId, String> {
        self.mir.hir[node.index()]
            .children
            .iter()
            .find(|e| e.role == role)
            .map(|e| e.node)
            .ok_or_else(|| format!("JS: missing {role:?} at {node:?}"))
    }
    fn sub(&mut self, node: HirId, role: Role) -> Result<String, String> {
        self.expr(self.child(node, role)?)
    }
    fn ty(&self, node: HirId) -> Result<&TypeConstructor, String> {
        let TypeState::Known(ty) = self.mir.ty_slots[node.index()] else {
            return Err("JS: unsealed type".into());
        };
        Ok(&self.mir.types[ty.index()].constructor)
    }
    fn expr(&mut self, node: HirId) -> Result<String, String> {
        if self.mir.value_adjustments[node.index()].is_some() {
            return Err(format!("JS prototype: value adjustment at {node:?}"));
        }
        let hir = &self.mir.hir[node.index()];
        Ok(match &hir.kind {
            HirKind::Int(x) => format!("{x}n"),
            HirKind::Float(x) => serde_json::to_string(x).map_err(|e| e.to_string())?,
            HirKind::String(x) => serde_json::to_string(x).unwrap(),
            HirKind::Binding {
                kind: BindingKind::Let | BindingKind::Def,
                ..
            } => self.sub(node, Role::Value)?,
            HirKind::Variable(_) => {
                let slot = hir.resolution.ok_or("JS: unresolved reference")?;
                let ResolveState::Bound(mut symbol) = self.mir.resolve_slots[slot.index()] else {
                    return Err("JS: unresolved reference".into());
                };
                let mut seen = BTreeSet::new();
                while let ResolveState::Bound(next) = self.mir.symbols[symbol.index()].resolution {
                    if next == symbol {
                        break;
                    }
                    if !seen.insert(symbol) {
                        return Err("JS: cyclic symbol alias".into());
                    }
                    symbol = next;
                }
                match self.mir.symbols[symbol.index()].kind {
                    SymbolKind::Parameter | SymbolKind::Pattern => format!("v{}", symbol.index()),
                    _ => {
                        if !self.locals.contains(&symbol) && self.globals.insert(symbol) {
                            self.pending.push(symbol);
                        }
                        format!("g{}()", symbol.index())
                    }
                }
            }
            HirKind::Closure => {
                let mut params = vec![];
                for edge in &hir.children {
                    if edge.role == Role::Parameter {
                        let symbol = self.mir.hir_symbols[edge.node.index()]
                            .ok_or("JS: missing parameter symbol")?;
                        params.push(format!("v{}", symbol.index()));
                    }
                }
                format!(
                    "(({}) => {})",
                    params.join(","),
                    self.sub(node, Role::Body)?
                )
            }
            HirKind::Call => {
                let callee = self.sub(node, Role::Callee)?;
                let args = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Argument)
                    .map(|e| self.expr(e.node))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("({callee})({})", args.join(","))
            }
            HirKind::Block => {
                let mut body = String::new();
                for edge in &hir.children {
                    if edge.role == Role::Binding {
                        let symbol = self.mir.hir_symbols[edge.node.index()]
                            .ok_or("JS: missing local symbol")?;
                        self.locals.insert(symbol);
                        // Locals are declared lexically, including within nested closures.
                        let value = self.expr(edge.node)?;
                        body.push_str(&format!(
                            "const v{} = {value}; const g{} = () => v{};",
                            symbol.index(),
                            symbol.index(),
                            symbol.index()
                        ));
                    }
                }
                format!(
                    "(() => {{{body}return {};}})()",
                    self.sub(node, Role::Result)?
                )
            }
            HirKind::If => format!(
                "({} ? {} : {})",
                self.sub(node, Role::Condition)?,
                self.sub(node, Role::Then)?,
                self.sub(node, Role::Else)?
            ),
            HirKind::Field
                if matches!(
                    self.mir.value_materializations[node.index()],
                    Some(ValueMaterialization::Boolean(_))
                ) =>
            {
                let Some(ValueMaterialization::Boolean(value)) =
                    self.mir.value_materializations[node.index()]
                else {
                    unreachable!()
                };
                value.to_string()
            }
            HirKind::Unary(op) => {
                let operand = self.child(node, Role::Operand)?;
                let token = match (op, self.ty(operand)?) {
                    (U::Negate, TypeConstructor::Int | TypeConstructor::Float) => "-",
                    (U::Not | U::LogicalNot, TypeConstructor::Bool) => "!",
                    (U::Not | U::BitNot, TypeConstructor::Int) => "~",
                    _ => return Err("JS prototype: unsupported unary operation".into()),
                };
                let value = format!("({token}{})", self.expr(operand)?);
                if self.ty(node)? == &TypeConstructor::Int {
                    format!("i64({value})")
                } else {
                    value
                }
            }
            HirKind::Binary(op) => {
                let left = self.child(node, Role::Left)?;
                if !matches!(
                    self.ty(left)?,
                    TypeConstructor::Int | TypeConstructor::Float | TypeConstructor::Bool
                ) {
                    return Err("JS prototype: only scalar binary operations supported".into());
                }
                let token = match op {
                    B::Add => "+",
                    B::Subtract => "-",
                    B::Multiply => "*",
                    B::Divide => "/",
                    B::Remainder => "%",
                    B::LessThan => "<",
                    B::LessThanOrEqual => "<=",
                    B::GreaterThan => ">",
                    B::GreaterThanOrEqual => ">=",
                    B::Equal => "===",
                    B::NotEqual => "!==",
                    B::And => "&&",
                    B::Or => "||",
                    B::BitAnd => "&",
                    B::BitOr => "|",
                    B::BitXor => "^",
                    _ => return Err("JS prototype: unsupported binary operation".into()),
                };
                let value = format!(
                    "({} {token} {})",
                    self.expr(left)?,
                    self.sub(node, Role::Right)?
                );
                if self.ty(node)? == &TypeConstructor::Int {
                    format!("i64({value})")
                } else {
                    value
                }
            }
            other => return Err(format!("JS prototype: unsupported {other:?} at {node:?}")),
        })
    }
}
