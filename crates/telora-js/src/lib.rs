mod metadata;
pub mod staging;
// Experimental direct JavaScript emission from sealed frontend evidence.
use std::collections::BTreeSet;
use telora_core::mir::*;
use telora_core::syntax::kinds::{BinaryOperator as B, BindingKind, UnaryOperator as U};

/// Emit a standalone ES module exporting the selected value as `default`.
/// Unsupported constructs fail compilation rather than falling back to Wasm.
pub fn compile_executable(executable: &SealedExecutable<'_>) -> Result<String, String> {
    compile_mode(executable, false)
}

pub fn compile_staging(executable: &SealedExecutable<'_>) -> Result<String, String> {
    compile_mode(executable, true)
}

fn compile_mode(executable: &SealedExecutable<'_>, staging: bool) -> Result<String, String> {
    let mir = executable.sealed_mir().mir();
    let mut emit = Emit {
        mir,
        globals: BTreeSet::new(),
        locals: BTreeSet::new(),
        pending: vec![],
        instance: None,
        staging,
        factories: std::collections::BTreeMap::new(),
    };
    let entry = emit.expr(executable.root())?;
    let metadata = metadata::emit(executable)?;
    let metadata = if staging {
        let json = metadata
            .strip_prefix("const types = ")
            .and_then(|s| s.strip_suffix(";\n"))
            .ok_or("invalid metadata")?;
        format!(
            "const types = JSON.parse({});\n",
            serde_json::to_string(json).map_err(|e| e.to_string())?
        )
    } else {
        metadata
    };
    let property_code = emit.properties(executable)?;
    let mut definitions = String::new();
    while let Some((symbol, instance)) = emit.pending.pop() {
        emit.instance = instance;
        let node = *mir.symbols[symbol.index()]
            .declarations
            .last()
            .ok_or("JS: missing declaration")?;
        let value = emit.expr(node)?;
        definitions.push_str(&format!(
            "const {} = memo(() => {value});\n",
            global_name(symbol, instance)
        ));
    }
    let factories = emit
        .factories
        .values()
        .cloned()
        .collect::<Vec<_>>()
        .join("\n");
    let stage_runtime = if staging {
        include_str!("staging.js")
    } else {
        ""
    };
    let stage_export = if staging {
        "export { stagePack, stageUnpack, buildInformation };"
    } else {
        ""
    };
    Ok(format!(
        "{RUNTIME}\n{COLLECTION_RUNTIME}\n{stage_runtime}\n{metadata}\n{property_code}\n{definitions}\n{factories}\nconst entry = {entry};\nexport default entry;\n{SERVICE_RUNTIME}\n{stage_export}\n"
    ))
}

const SERVICE_RUNTIME: &str = include_str!("service.js");

const COLLECTION_RUNTIME: &str = include_str!("runtime.js");

const RUNTIME: &str = r#"// Generated by the experimental Telora JS backend
const i64 = x => {
  if (x < -9223372036854775808n || x > 9223372036854775807n)
    throw new RangeError('Telora Int overflow');
  return x;
};
const variant = (tag, value) => Object.freeze({tag, value});
const equal = (a,b) => {
  if (a === b) return true;
  if (a === null || b === null || typeof a !== 'object' || typeof b !== 'object') return false;
  const keys = Object.keys(a), other = Object.keys(b);
  return keys.length === other.length && keys.every(k => Object.hasOwn(b,k) && equal(a[k],b[k]));
};
const index = (a,i) => {
  if (!Object.hasOwn(a, i)) throw new RangeError('Telora invalid index');
  return a[i];
};
const memo = f => {
  let state = 0, value;
  const getter = () => {
    if (state === 2) return value;
    if (state === 1) throw new Error('Telora cyclic initialization');
    state = 1;
    try { value = f(); state = 2; return value; }
    catch (error) { state = 0; throw error; }
  };
  return typeof stageDescribe==='function'?stageDescribe(getter,()=>state===2?({kind:'memo',state,value}):({kind:'memo',state,calc:f})):getter;
};
"#;

fn global_name(symbol: SymbolId, instance: Option<GenericInstanceId>) -> String {
    format!(
        "g{}_{}",
        symbol.index(),
        instance
            .map(|x| x.index().to_string())
            .unwrap_or_else(|| "v".into())
    )
}

struct Emit<'a> {
    staging: bool,
    factories: std::collections::BTreeMap<String, String>,
    instance: Option<GenericInstanceId>,
    mir: &'a Mir,
    globals: BTreeSet<(SymbolId, Option<GenericInstanceId>)>,
    pending: Vec<(SymbolId, Option<GenericInstanceId>)>,
    locals: BTreeSet<SymbolId>,
}
impl Emit<'_> {
    fn captures(&self, node: HirId) -> Vec<SymbolId> {
        let mut pending = vec![node];
        let mut defined = BTreeSet::new();
        let mut used = BTreeSet::new();
        while let Some(n) = pending.pop() {
            let h = &self.mir.hir[n.index()];
            if let Some(s) = self.mir.hir_symbols[n.index()] {
                defined.insert(s);
            }
            if let Some(slot) = h.resolution {
                if let ResolveState::Bound(mut s) = self.mir.resolve_slots[slot.index()] {
                    let mut seen = BTreeSet::new();
                    while let ResolveState::Bound(next) = self.mir.symbols[s.index()].resolution {
                        if next == s || !seen.insert(s) {
                            break;
                        }
                        s = next;
                    }
                    if self.locals.contains(&s)
                        || matches!(
                            self.mir.symbols[s.index()].kind,
                            SymbolKind::Parameter | SymbolKind::Pattern
                        )
                    {
                        used.insert(s);
                    }
                }
            }
            pending.extend(h.children.iter().map(|e| e.node));
        }
        used.difference(&defined).copied().collect()
    }
    fn child(&self, node: HirId, role: Role) -> Result<HirId, String> {
        self.mir.hir[node.index()]
            .children
            .iter()
            .find(|e| e.role == role)
            .map(|e| e.node)
            .ok_or_else(|| format!("JS: missing {role:?} at {node:?}"))
    }
    fn sub(&mut self, node: HirId, role: Role) -> Result<String, String> {
        self.expr(self.child(node, role)?)
    }
    fn ty(&self, node: HirId) -> Result<&TypeConstructor, String> {
        let ty = self.type_id(node)?;
        Ok(&self.mir.types[ty.index()].constructor)
    }
    fn type_id(&self, node: HirId) -> Result<TypeId, String> {
        if let Some(id) = self.instance {
            if let Some(ty) = self.mir.generic_instances[id.index()].ty(node) {
                return Ok(ty);
            }
        }
        match self.mir.ty_slots[node.index()] {
            TypeState::Known(ty) => Ok(ty),
            _ => Err(format!(
                "JS: unsealed type at {node:?} in {:?}",
                self.instance
            )),
        }
    }
    fn reference(&self, node: HirId) -> Option<GenericInstanceId> {
        match self.instance {
            Some(id) => self.mir.generic_instances[id.index()].reference(node),
            None => self.mir.generic_references[node.index()].and_then(|r| r.instance()),
        }
    }
    fn expr(&mut self, node: HirId) -> Result<String, String> {
        let hir = &self.mir.hir[node.index()];
        if let Some(value) = self.mir.value_materializations[node.index()] {
            return match value {
                ValueMaterialization::Boolean(x) => Ok(x.to_string()),
                ValueMaterialization::EnumVariant { index } => {
                    let ty = self.type_id(node)?;
                    if self.mir.types[ty.index()].constructor == TypeConstructor::Function {
                        if self.staging {
                            Ok(format!("stageBuiltin('variant', [{index}])"))
                        } else {
                            Ok(format!("(x => variant({index}, x))"))
                        }
                    } else {
                        Ok(format!("variant({index})"))
                    }
                }
                ValueMaterialization::NewtypeConstructor => {
                    let ty = self.type_id(node)?;
                    let owner = self.mir.types[ty.index()]
                        .arguments
                        .last()
                        .ok_or("JS: missing newtype owner")?;
                    Ok(if self.staging {
                        format!("stageBuiltin('check', [{}])", owner.index())
                    } else {
                        format!("(x => check({}, 'type', x))", owner.index())
                    })
                }
            };
        }
        Ok(match &hir.kind {
            HirKind::Binding {
                kind: BindingKind::Native,
                ..
            } => {
                let symbol =
                    self.mir.hir_symbols[node.index()].ok_or("JS: missing native symbol")?;
                let symbol = &self.mir.symbols[symbol.index()];
                let module = self.mir.modules
                    [symbol.module.ok_or("JS: missing native module")?.index()]
                .native
                .as_ref()
                .ok_or("JS: untrusted native declaration")?;
                let key = format!("{}:{}", module.id, symbol.name);
                if module.id == 25 && matches!(symbol.name.as_str(), "required" | "optional") {
                    let instance = self.instance.ok_or("JS: missing property instance")?;
                    let record = &self.mir.generic_instances[instance.index()];
                    let params = &self.mir.symbol_generics[record.symbol.index()];
                    let arg = |i: usize| {
                        record
                            .arguments
                            .iter()
                            .find(|(s, _)| *s == params[i])
                            .map(|(_, t)| t.index())
                            .ok_or("JS: missing property argument")
                    };
                    if self.staging {
                        return Ok(format!(
                            "stageBuiltin('property', [{}, 'type', {}, {}])",
                            arg(1)?,
                            arg(0)?,
                            symbol.name == "required"
                        ));
                    }
                    return Ok(format!(
                        "(() => property({}, 'type', {}, {}))",
                        arg(1)?,
                        arg(0)?,
                        symbol.name == "required"
                    ));
                }

                if !COLLECTION_RUNTIME.contains(&format!("'{}':", key)) {
                    return Err(format!("JS: unsupported native {key}"));
                }
                format!(
                    "native({}, {})",
                    serde_json::to_string(&key).unwrap(),
                    self.type_id(node)?.index()
                )
            }
            HirKind::Int(x) => format!("{x}n"),
            HirKind::Float(x) => serde_json::to_string(x).map_err(|e| e.to_string())?,
            HirKind::String(x) => serde_json::to_string(x).unwrap(),
            HirKind::InterpolatedString => {
                let parts = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Part)
                    .map(|e| self.expr(e.node))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("[{}].join('')", parts.join(","))
            }

            HirKind::Binding {
                kind: BindingKind::Type,
                ..
            } => {
                let ty = self
                    .instance
                    .map(|id| self.mir.generic_instances[id.index()].signature)
                    .unwrap_or(self.type_id(node)?);
                let shape = &self.mir.types[ty.index()];
                if shape.constructor == TypeConstructor::Function {
                    let owner = shape
                        .arguments
                        .last()
                        .ok_or("JS: missing constructor result")?;
                    if self.staging {
                        format!("stageBuiltin('check', [{}])", owner.index())
                    } else {
                        format!("(value => check({}, 'type', value))", owner.index())
                    }
                } else if shape.constructor == TypeConstructor::Meta {
                    shape
                        .arguments
                        .first()
                        .ok_or("JS: missing type value")?
                        .index()
                        .to_string()
                } else if matches!(shape.constructor, TypeConstructor::Nominal(_)) {
                    ty.index().to_string()
                } else {
                    return Err(format!(
                        "JS: type declaration used as value at {node:?}: {shape:?}, instance {:?}",
                        self.instance
                    ));
                }
            }
            HirKind::Binding {
                kind: BindingKind::Let | BindingKind::Def | BindingKind::Impl,
                ..
            } => self.sub(node, Role::Value)?,
            HirKind::TypeApply if self.reference(node).is_none() => self.sub(node, Role::Callee)?,
            HirKind::Variable(_) | HirKind::TypeApply | HirKind::Field
                if !matches!(
                    self.mir.member_selections[node.index()],
                    Some(MemberSelection::TraitMember { .. })
                ) && (!matches!(hir.kind, HirKind::Field)
                    || hir.resolution.is_some_and(|slot| {
                        matches!(self.mir.resolve_slots[slot.index()], ResolveState::Bound(_))
                    })) =>
            {
                if let Some(instance) = self.reference(node) {
                    let symbol = self.mir.generic_instances[instance.index()].symbol;
                    if self.globals.insert((symbol, Some(instance))) {
                        self.pending.push((symbol, Some(instance)));
                    }
                    return Ok(format!("{}()", global_name(symbol, Some(instance))));
                }
                let slot = hir.resolution.ok_or("JS: unresolved reference")?;
                let ResolveState::Bound(mut symbol) = self.mir.resolve_slots[slot.index()] else {
                    return Err("JS: unresolved reference".into());
                };
                let mut seen = BTreeSet::new();
                while let ResolveState::Bound(next) = self.mir.symbols[symbol.index()].resolution {
                    if next == symbol {
                        break;
                    }
                    if !seen.insert(symbol) {
                        return Err("JS: cyclic symbol alias".into());
                    }
                    symbol = next;
                }
                match self.mir.symbols[symbol.index()].kind {
                    SymbolKind::Parameter | SymbolKind::Pattern => format!("v{}", symbol.index()),
                    _ => {
                        if !self.locals.contains(&symbol) && self.globals.insert((symbol, None)) {
                            self.pending.push((symbol, None));
                        }
                        format!("{}()", global_name(symbol, None))
                    }
                }
            }
            HirKind::TypeAscription => {
                if let Ok(value) = self.child(node, Role::Value) {
                    format!(
                        "check({}, 'type', {})",
                        self.type_id(node)?.index(),
                        self.expr(value)?
                    )
                } else {
                    self.sub(node, Role::Receiver)?
                }
            }
            HirKind::TypeMetadata => {
                let ty = self.type_id(node)?;
                let value = self.mir.types[ty.index()]
                    .arguments
                    .first()
                    .ok_or("JS: missing metadata target")?;
                format!("{}", value.index())
            }
            HirKind::Array | HirKind::Tuple => {
                let values = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Item)
                    .map(|e| self.expr(e.node))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("Object.freeze([{}])", values.join(","))
            }
            HirKind::Spread => format!("...{}", self.sub(node, Role::Operand)?),
            HirKind::Dict => {
                let mut fields = vec![];
                for edge in &hir.children {
                    if edge.role != Role::Field {
                        continue;
                    }
                    let field = edge.node;
                    let value = self.sub(field, Role::Value)?;
                    if let Ok(name) = self.child(field, Role::Name) {
                        let HirKind::Name(name) = &self.mir.hir[name.index()].kind else {
                            return Err("JS: missing field name".into());
                        };
                        fields.push(format!(
                            "[{}]:{value}",
                            serde_json::to_string(name).unwrap()
                        ));
                    } else {
                        fields.push(value);
                    }
                }
                format!("Object.freeze({{{}}})", fields.join(","))
            }
            HirKind::Field => {
                if let Some(MemberSelection::TraitMember { implementation, .. }) =
                    self.mir.member_selections[node.index()]
                {
                    let instance = match self.instance {
                        Some(id) => self.mir.generic_instances[id.index()].implementation(node),
                        None => self.mir.implementation_instances[node.index()],
                    };
                    let symbol = instance
                        .map(|id| self.mir.generic_instances[id.index()].symbol)
                        .or(implementation)
                        .ok_or("JS: missing trait implementation")?;
                    if self.globals.insert((symbol, instance)) {
                        self.pending.push((symbol, instance));
                    }
                    let HirKind::Name(name) =
                        &self.mir.hir[self.child(node, Role::Name)?.index()].kind
                    else {
                        return Err("JS: missing trait member".into());
                    };
                    format!(
                        "{}()[{}]",
                        global_name(symbol, instance),
                        serde_json::to_string(name).unwrap()
                    )
                } else {
                    let receiver = self.sub(node, Role::Receiver)?;
                    let HirKind::Name(name) =
                        &self.mir.hir[self.child(node, Role::Name)?.index()].kind
                    else {
                        return Err("JS: missing member name".into());
                    };
                    format!("({receiver})[{}]", serde_json::to_string(name).unwrap())
                }
            }
            HirKind::TupleProjection(index) => {
                let receiver = self.child(node, Role::Receiver)?;
                let ty = self.type_id(receiver)?;
                let body = self.mir.type_layouts[ty.index()].as_ref().map(|x| x.body);
                let newtype = body.is_some_and(|b| {
                    self.mir.types[b.index()].constructor == TypeConstructor::Newtype
                });
                if newtype {
                    self.expr(receiver)?
                } else {
                    format!("({})[{index}]", self.expr(receiver)?)
                }
            }
            HirKind::FieldProjection => {
                let receiver = self.sub(node, Role::Receiver)?;
                let sources = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Name)
                    .map(|e| e.node)
                    .collect::<Vec<_>>();
                let targets = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Target)
                    .map(|e| e.node)
                    .collect::<Vec<_>>();
                let mut fields = vec![];
                for (source, target) in sources.iter().zip(targets) {
                    let (HirKind::Name(source), HirKind::Name(target)) = (
                        &self.mir.hir[source.index()].kind,
                        &self.mir.hir[target.index()].kind,
                    ) else {
                        return Err("JS: missing projection name".into());
                    };
                    fields.push(format!(
                        "[{}]:value[{}]",
                        serde_json::to_string(target).unwrap(),
                        serde_json::to_string(source).unwrap()
                    ));
                }
                format!(
                    "((value)=>Object.freeze({{{}}}))({receiver})",
                    fields.join(",")
                )
            }
            HirKind::Index => format!(
                "index({}, {})",
                self.sub(node, Role::Receiver)?,
                self.sub(node, Role::Index)?
            ),
            HirKind::Match => self.match_expr(node)?,
            HirKind::IfLet | HirKind::LetElse => {
                let input = self.sub(node, Role::Value)?;
                let mut bindings = String::new();
                let cond =
                    self.pattern(self.child(node, Role::Pattern)?, "matched", &mut bindings)?;
                let yes = self.sub(
                    node,
                    if matches!(hir.kind, HirKind::IfLet) {
                        Role::Then
                    } else {
                        Role::Body
                    },
                )?;
                let no = self.sub(node, Role::Else)?;
                format!(
                    "(() => {{const matched={input}; if({cond}){{{bindings}return {yes};}}return {no};}})()"
                )
            }

            HirKind::Panic | HirKind::Raise(_) => {
                use telora_core::syntax::kinds::BlameAction;
                let value = self.sub(node, Role::Value)?;
                let file = self.mir.sources.get(hir.location.source);
                let coords = file.coordinates(hir.location).0;
                let location = format!(
                    "Object.freeze({{source:{},start:Object.freeze({{line:{}n,offset:{}n}}),end:Object.freeze({{line:{}n,offset:{}n}})}})",
                    serde_json::to_string(file.name.as_ref()).unwrap(),
                    coords[1] + 1,
                    coords[2],
                    coords[3] + 1,
                    coords[4]
                );
                match hir.kind {
                    HirKind::Raise(BlameAction::Build) => {
                        format!(
                            "Object.freeze({{message:{value},locs:Object.freeze([{location}])}})"
                        )
                    }
                    HirKind::Raise(BlameAction::Warn) => format!("warning({value}, [{location}])"),
                    _ => format!("failure({value}, [{location}])"),
                }
            }
            HirKind::Debug { .. } => self.sub(node, Role::Value)?,
            HirKind::Decorator { configured } | HirKind::ConstructionCheck { configured } => {
                let callee = self.sub(node, Role::Callee)?;
                if *configured {
                    let args = hir
                        .children
                        .iter()
                        .filter(|e| e.role == Role::Argument)
                        .map(|e| self.expr(e.node))
                        .collect::<Result<Vec<_>, _>>()?;
                    format!("({callee})({})", args.join(","))
                } else {
                    callee
                }
            }
            HirKind::Interpreter => {
                let plan = self.mir.interpreter_plans[node.index()]
                    .as_ref()
                    .ok_or("JS: missing interpreter plan")?;
                let inputs = plan
                    .parameters
                    .iter()
                    .enumerate()
                    .map(|(i, w)| match w {
                        Some(w) => format!("Object.freeze({{ty:ws[{w}],value:xs[{i}]}})"),
                        None => format!("xs[{i}]"),
                    })
                    .collect::<Vec<_>>();
                format!(
                    "((f) => (...ws) => (...xs) => f({}))({})",
                    inputs.join(","),
                    self.sub(node, Role::Operand)?
                )
            }
            HirKind::Propagate => {
                let boundary = self.mir.propagation_boundaries[node.index()]
                    .ok_or("JS: missing propagation boundary")?;
                format!(
                    "propagate({}, {})",
                    self.sub(node, Role::Operand)?,
                    boundary.index()
                )
            }
            HirKind::Return => {
                let boundary = self.mir.propagation_boundaries[node.index()]
                    .ok_or("JS: missing return boundary")?;
                format!(
                    "escape({}, {})",
                    self.sub(node, Role::Value)?,
                    boundary.index()
                )
            }
            HirKind::Closure => {
                let mut params = vec![];
                for edge in &hir.children {
                    if edge.role == Role::Parameter {
                        let symbol = self.mir.hir_symbols[edge.node.index()]
                            .ok_or("JS: missing parameter symbol")?;
                        params.push(format!("v{}", symbol.index()));
                    }
                }
                let body = self.sub(node, Role::Body)?;
                let function = format!(
                    "(({}) => boundary({}, () => {}))",
                    params.join(","),
                    node.index(),
                    body
                );
                if !self.staging {
                    function
                } else {
                    let captures = self.captures(node);
                    let names = captures
                        .iter()
                        .map(|s| format!("v{}", s.index()))
                        .collect::<Vec<_>>();
                    let aliases = captures
                        .iter()
                        .map(|s| format!("const {} = () => v{};", global_name(*s, None), s.index()))
                        .collect::<String>();
                    let id = format!(
                        "c{}_{}",
                        node.index(),
                        self.instance
                            .map(|x| x.index().to_string())
                            .unwrap_or_else(|| "v".into())
                    );
                    self.factories.insert(
                        id.clone(),
                        format!(
                            "stageFactories[{id:?}] = ([{}]) => {{{aliases}return {function};}};",
                            names.join(",")
                        ),
                    );
                    format!("stageClosure({id:?}, () => [{}])", names.join(","))
                }
            }
            HirKind::Call => {
                let callee = self.sub(node, Role::Callee)?;
                let args = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Argument)
                    .map(|e| self.expr(e.node))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("({callee})({})", args.join(","))
            }
            HirKind::Block => {
                let mut body = String::new();
                for edge in &hir.children {
                    if edge.role == Role::Binding {
                        let symbol = self.mir.hir_symbols[edge.node.index()]
                            .ok_or("JS: missing local symbol")?;
                        self.locals.insert(symbol);
                        // Locals are declared lexically, including within nested closures.
                        let value = self.expr(edge.node)?;
                        body.push_str(&format!(
                            "const v{} = {value}; const {} = () => v{};",
                            symbol.index(),
                            global_name(symbol, None),
                            symbol.index()
                        ));
                    }
                }
                format!(
                    "(() => {{{body}return {};}})()",
                    self.sub(node, Role::Result)?
                )
            }
            HirKind::If => format!(
                "({} ? {} : {})",
                self.sub(node, Role::Condition)?,
                self.sub(node, Role::Then)?,
                self.sub(node, Role::Else)?
            ),
            HirKind::Unary(op) => {
                let operand = self.child(node, Role::Operand)?;
                let token = match (op, self.ty(operand)?) {
                    (U::Negate, TypeConstructor::Int | TypeConstructor::Float) => "-",
                    (U::Not | U::LogicalNot, TypeConstructor::Bool) => "!",
                    (U::Not | U::BitNot, TypeConstructor::Int) => "~",
                    _ => return Err("JS prototype: unsupported unary operation".into()),
                };
                let value = format!("({token}{})", self.expr(operand)?);
                if self.ty(node)? == &TypeConstructor::Int {
                    format!("i64({value})")
                } else {
                    value
                }
            }
            HirKind::Binary(op) => {
                let left = self.child(node, Role::Left)?;
                if *op == B::StructUpdate {
                    return Ok(format!(
                        "Object.freeze({{...{}, ...{}}})",
                        self.expr(left)?,
                        self.sub(node, Role::Right)?
                    ));
                }
                if matches!(op, B::Equal | B::NotEqual) {
                    return Ok(format!(
                        "{}equal({}, {})",
                        if *op == B::NotEqual { "!" } else { "" },
                        self.expr(left)?,
                        self.sub(node, Role::Right)?
                    ));
                }
                if !matches!(
                    self.ty(left)?,
                    TypeConstructor::Int
                        | TypeConstructor::Float
                        | TypeConstructor::Bool
                        | TypeConstructor::String
                ) {
                    return Err("JS prototype: only scalar binary operations supported".into());
                }
                let token = match op {
                    B::Add => "+",
                    B::Subtract => "-",
                    B::Multiply => "*",
                    B::Divide => "/",
                    B::Remainder => "%",
                    B::LessThan => "<",
                    B::LessThanOrEqual => "<=",
                    B::GreaterThan => ">",
                    B::GreaterThanOrEqual => ">=",
                    B::Equal => "===",
                    B::NotEqual => "!==",
                    B::And => "&&",
                    B::Or => "||",
                    B::BitAnd => "&",
                    B::BitOr => "|",
                    B::BitXor => "^",
                    _ => return Err("JS prototype: unsupported binary operation".into()),
                };
                let value = format!(
                    "({} {token} {})",
                    self.expr(left)?,
                    self.sub(node, Role::Right)?
                );
                if self.ty(node)? == &TypeConstructor::Int {
                    format!("i64({value})")
                } else {
                    value
                }
            }
            other => return Err(format!("JS prototype: unsupported {other:?} at {node:?}")),
        })
    }
}

impl Emit<'_> {
    fn pattern(&self, node: HirId, value: &str, bindings: &mut String) -> Result<String, String> {
        let hir = &self.mir.hir[node.index()];
        if let Some(selected) = self.mir.member_selections[node.index()] {
            match selected {
                MemberSelection::Boolean(x) => return Ok(format!("{value} === {x}")),
                MemberSelection::EnumVariant { index } => {
                    let mut cond = format!("{value}.tag === {index}");
                    if let Ok(pat) = self.child(node, Role::Pattern) {
                        cond.push_str(&format!(
                            " && ({})",
                            self.pattern(pat, &format!("{value}.value"), bindings)?
                        ));
                    }
                    return Ok(cond);
                }
                MemberSelection::NewtypePattern => {
                    return self.pattern(self.child(node, Role::Pattern)?, value, bindings);
                }
                _ => {}
            }
        }
        match &hir.kind {
            HirKind::Wildcard => Ok("true".into()),
            HirKind::PatternName(_) => {
                let symbol =
                    self.mir.hir_symbols[node.index()].ok_or("JS: missing pattern symbol")?;
                bindings.push_str(&format!("const v{} = {value};", symbol.index()));
                Ok("true".into())
            }
            HirKind::Int(x) => Ok(format!("{value} === {x}n")),
            HirKind::String(x) => Ok(format!("{value} === {}", serde_json::to_string(x).unwrap())),
            HirKind::TuplePattern | HirKind::StructPattern => {
                let mut cond = vec![];
                for (i, edge) in hir
                    .children
                    .iter()
                    .filter(|e| matches!(e.role, Role::Item | Role::Field))
                    .enumerate()
                {
                    let (pat, field) = if edge.role == Role::Item {
                        (edge.node, i.to_string())
                    } else {
                        let HirKind::Name(name) =
                            &self.mir.hir[self.child(edge.node, Role::Name)?.index()].kind
                        else {
                            return Err("JS: missing pattern field".into());
                        };
                        (
                            self.child(edge.node, Role::Pattern)?,
                            serde_json::to_string(name).unwrap(),
                        )
                    };
                    cond.push(self.pattern(pat, &format!("{value}[{field}]"), bindings)?);
                }
                Ok(if cond.is_empty() {
                    "true".into()
                } else {
                    cond.join(" && ")
                })
            }
            other => Err(format!("JS: unsupported pattern {other:?}")),
        }
    }
    fn match_expr(&mut self, node: HirId) -> Result<String, String> {
        let input = self.sub(node, Role::Value)?;
        let mut body = format!("const matched = {input};");
        for edge in self.mir.hir[node.index()]
            .children
            .iter()
            .filter(|e| e.role == Role::Arm)
        {
            let mut bindings = String::new();
            let cond = self.pattern(
                self.child(edge.node, Role::Pattern)?,
                "matched",
                &mut bindings,
            )?;
            let guard = if self.child(edge.node, Role::Guard).is_ok() {
                self.sub(edge.node, Role::Guard)?
            } else {
                "true".into()
            };
            let result = self.sub(edge.node, Role::Value)?;
            body.push_str(&format!(
                "if ({cond}) {{{bindings}if ({guard}) return {result};}}"
            ));
        }
        Ok(format!(
            "(() => {{{body}throw new Error('Telora nonexhaustive match');}})()"
        ))
    }
}

impl Emit<'_> {
    fn properties(&mut self, executable: &SealedExecutable<'_>) -> Result<String, String> {
        let mut code = String::from(
            "const properties = Object.create(null);\nconst checkers = Object.create(null);\n",
        );
        for &i in executable.properties() {
            let record = &self.mir.properties[i];
            self.instance = record.instance;
            let site = match record.site {
                PropertySite::Type => "type".into(),
                PropertySite::Field(i) => format!("field:{i}"),
                PropertySite::Variant(i) => format!("variant:{i}"),
            };
            let context = match record.site {
                PropertySite::Type => record.owner.index().to_string(),
                PropertySite::Field(index) | PropertySite::Variant(index) => format!(
                    "propertyContext({}, {}, {})",
                    record.owner.index(),
                    index,
                    matches!(record.site, PropertySite::Variant(_))
                ),
            };
            let mut value = "none()".to_string();
            for &provider in &record.providers {
                let provider = self.expr(provider)?;
                value = format!("some(({provider})({context}, {value}))");
            }
            let key = serde_json::to_string(&format!(
                "{}:{site}:{}",
                record.owner.index(),
                record.property.index()
            ))
            .unwrap();
            code.push_str(&format!(
                "properties[{key}] = memo(() => ({value}).value);\n"
            ));
        }
        for &i in executable.checks() {
            let record = &self.mir.construction_checks[i];
            self.instance = record.instance;
            let callee = self.expr(record.checker)?;
            let site = match record.site {
                PropertySite::Type => "type".into(),
                PropertySite::Field(i) => format!("field:{i}"),
                PropertySite::Variant(i) => format!("variant:{i}"),
            };
            let key = serde_json::to_string(&format!("{}:{site}", record.owner.index())).unwrap();
            code.push_str(&format!(
                "(checkers[{key}] ??= []).push(memo(() => {callee}));\n"
            ));
        }
        self.instance = None;
        Ok(code)
    }
}
