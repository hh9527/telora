//! Experimental direct JavaScript emission from sealed frontend evidence.
use std::collections::BTreeSet;
use telora_core::mir::*;
use telora_core::syntax::kinds::{BinaryOperator as B, BindingKind, UnaryOperator as U};

/// Emit a standalone ES module exporting the selected value as `default`.
/// Unsupported constructs fail compilation rather than falling back to Wasm.
pub fn compile_executable(executable: &SealedExecutable<'_>) -> Result<String, String> {
    if !executable.checks().is_empty() {
        return Err("JS prototype: construction checks are unsupported".into());
    }
    let mir = executable.sealed_mir().mir();
    let mut emit = Emit {
        mir,
        globals: BTreeSet::new(),
        locals: BTreeSet::new(),
        pending: vec![],
        instance: None,
    };
    let entry = emit.expr(executable.root())?;
    let mut definitions = String::new();
    while let Some((symbol, instance)) = emit.pending.pop() {
        emit.instance = instance;
        let node = *mir.symbols[symbol.index()]
            .declarations
            .last()
            .ok_or("JS: missing declaration")?;
        let value = emit.expr(node)?;
        definitions.push_str(&format!(
            "const {} = memo(() => {value});\n",
            global_name(symbol, instance)
        ));
    }
    Ok(format!(
        "{RUNTIME}\n{COLLECTION_RUNTIME}\n{definitions}\nexport default {entry};\n"
    ))
}

const COLLECTION_RUNTIME: &str = include_str!("runtime.js");

const RUNTIME: &str = r#"// Generated by the experimental Telora JS backend
const i64 = x => {
  if (x < -9223372036854775808n || x > 9223372036854775807n)
    throw new RangeError('Telora Int overflow');
  return x;
};
const variant = (tag, value) => Object.freeze({tag, value});
const equal = (a,b) => {
  if (a === b) return true;
  if (a === null || b === null || typeof a !== 'object' || typeof b !== 'object') return false;
  const keys = Object.keys(a), other = Object.keys(b);
  return keys.length === other.length && keys.every(k => Object.hasOwn(b,k) && equal(a[k],b[k]));
};
const index = (a,i) => {
  if (!Object.hasOwn(a, i)) throw new RangeError('Telora invalid index');
  return a[i];
};
const memo = f => {
  let state = 0, value;
  return () => {
    if (state === 2) return value;
    if (state === 1) throw new Error('Telora cyclic initialization');
    state = 1;
    try { value = f(); state = 2; return value; }
    catch (error) { state = 0; throw error; }
  };
};
"#;

fn global_name(symbol: SymbolId, instance: Option<GenericInstanceId>) -> String {
    format!(
        "g{}_{}",
        symbol.index(),
        instance
            .map(|x| x.index().to_string())
            .unwrap_or_else(|| "v".into())
    )
}

struct Emit<'a> {
    instance: Option<GenericInstanceId>,
    mir: &'a Mir,
    globals: BTreeSet<(SymbolId, Option<GenericInstanceId>)>,
    pending: Vec<(SymbolId, Option<GenericInstanceId>)>,
    locals: BTreeSet<SymbolId>,
}
impl Emit<'_> {
    fn child(&self, node: HirId, role: Role) -> Result<HirId, String> {
        self.mir.hir[node.index()]
            .children
            .iter()
            .find(|e| e.role == role)
            .map(|e| e.node)
            .ok_or_else(|| format!("JS: missing {role:?} at {node:?}"))
    }
    fn sub(&mut self, node: HirId, role: Role) -> Result<String, String> {
        self.expr(self.child(node, role)?)
    }
    fn ty(&self, node: HirId) -> Result<&TypeConstructor, String> {
        let ty = self.type_id(node)?;
        Ok(&self.mir.types[ty.index()].constructor)
    }
    fn type_id(&self, node: HirId) -> Result<TypeId, String> {
        if let Some(id) = self.instance {
            if let Some(ty) = self.mir.generic_instances[id.index()].ty(node) {
                return Ok(ty);
            }
        }
        match self.mir.ty_slots[node.index()] {
            TypeState::Known(ty) => Ok(ty),
            _ => Err(format!(
                "JS: unsealed type at {node:?} in {:?}",
                self.instance
            )),
        }
    }
    fn reference(&self, node: HirId) -> Option<GenericInstanceId> {
        match self.instance {
            Some(id) => self.mir.generic_instances[id.index()].reference(node),
            None => self.mir.generic_references[node.index()].and_then(|r| r.instance()),
        }
    }
    fn expr(&mut self, node: HirId) -> Result<String, String> {
        let hir = &self.mir.hir[node.index()];
        if let Some(value) = self.mir.value_materializations[node.index()] {
            return match value {
                ValueMaterialization::Boolean(x) => Ok(x.to_string()),
                ValueMaterialization::EnumVariant { index } => {
                    let ty = self.type_id(node)?;
                    if self.mir.types[ty.index()].constructor == TypeConstructor::Function {
                        Ok(format!("(x => variant({index}, x))"))
                    } else {
                        Ok(format!("variant({index})"))
                    }
                }
                ValueMaterialization::NewtypeConstructor => Ok("(x => x)".into()),
            };
        }
        Ok(match &hir.kind {
            HirKind::Binding {
                kind: BindingKind::Native,
                ..
            } => {
                let symbol =
                    self.mir.hir_symbols[node.index()].ok_or("JS: missing native symbol")?;
                let symbol = &self.mir.symbols[symbol.index()];
                let module = self.mir.modules
                    [symbol.module.ok_or("JS: missing native module")?.index()]
                .native
                .as_ref()
                .ok_or("JS: untrusted native declaration")?;
                let key = format!("{}:{}", module.id, symbol.name);
                if !COLLECTION_RUNTIME.contains(&format!("'{}':", key)) {
                    return Err(format!("JS: unsupported native {key}"));
                }
                format!(
                    "native({}, {})",
                    serde_json::to_string(&key).unwrap(),
                    self.type_id(node)?.index()
                )
            }
            HirKind::Int(x) => format!("{x}n"),
            HirKind::Float(x) => serde_json::to_string(x).map_err(|e| e.to_string())?,
            HirKind::String(x) => serde_json::to_string(x).unwrap(),
            HirKind::Binding {
                kind: BindingKind::Let | BindingKind::Def | BindingKind::Impl,
                ..
            } => self.sub(node, Role::Value)?,
            HirKind::TypeApply if self.reference(node).is_none() => self.sub(node, Role::Callee)?,
            HirKind::Variable(_) | HirKind::TypeApply | HirKind::Field
                if !matches!(hir.kind, HirKind::Field)
                    || hir.resolution.is_some_and(|slot| {
                        matches!(self.mir.resolve_slots[slot.index()], ResolveState::Bound(_))
                    }) =>
            {
                if let Some(instance) = self.reference(node) {
                    let symbol = self.mir.generic_instances[instance.index()].symbol;
                    if self.globals.insert((symbol, Some(instance))) {
                        self.pending.push((symbol, Some(instance)));
                    }
                    return Ok(format!("{}()", global_name(symbol, Some(instance))));
                }
                let slot = hir.resolution.ok_or("JS: unresolved reference")?;
                let ResolveState::Bound(mut symbol) = self.mir.resolve_slots[slot.index()] else {
                    return Err("JS: unresolved reference".into());
                };
                let mut seen = BTreeSet::new();
                while let ResolveState::Bound(next) = self.mir.symbols[symbol.index()].resolution {
                    if next == symbol {
                        break;
                    }
                    if !seen.insert(symbol) {
                        return Err("JS: cyclic symbol alias".into());
                    }
                    symbol = next;
                }
                match self.mir.symbols[symbol.index()].kind {
                    SymbolKind::Parameter | SymbolKind::Pattern => format!("v{}", symbol.index()),
                    _ => {
                        if !self.locals.contains(&symbol) && self.globals.insert((symbol, None)) {
                            self.pending.push((symbol, None));
                        }
                        format!("{}()", global_name(symbol, None))
                    }
                }
            }
            HirKind::TypeAscription => {
                if let Ok(value) = self.child(node, Role::Value) {
                    self.expr(value)?
                } else {
                    self.sub(node, Role::Receiver)?
                }
            }
            HirKind::TypeMetadata => {
                let ty = self.type_id(node)?;
                let value = self.mir.types[ty.index()]
                    .arguments
                    .first()
                    .ok_or("JS: missing metadata target")?;
                format!("{}", value.index())
            }
            HirKind::Array | HirKind::Tuple => {
                let values = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Item)
                    .map(|e| self.expr(e.node))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("Object.freeze([{}])", values.join(","))
            }
            HirKind::Spread => format!("...{}", self.sub(node, Role::Operand)?),
            HirKind::Dict => {
                let mut fields = vec![];
                for edge in &hir.children {
                    if edge.role != Role::Field {
                        continue;
                    }
                    let field = edge.node;
                    let value = self.sub(field, Role::Value)?;
                    if let Ok(name) = self.child(field, Role::Name) {
                        let HirKind::Name(name) = &self.mir.hir[name.index()].kind else {
                            return Err("JS: missing field name".into());
                        };
                        fields.push(format!(
                            "[{}]:{value}",
                            serde_json::to_string(name).unwrap()
                        ));
                    } else {
                        fields.push(value);
                    }
                }
                format!("Object.freeze({{{}}})", fields.join(","))
            }
            HirKind::Field => {
                if let Some(MemberSelection::TraitMember {
                    implementation: Some(symbol),
                    ..
                }) = self.mir.member_selections[node.index()]
                {
                    let instance = match self.instance {
                        Some(id) => self.mir.generic_instances[id.index()].implementation(node),
                        None => self.mir.implementation_instances[node.index()],
                    };
                    if self.globals.insert((symbol, instance)) {
                        self.pending.push((symbol, instance));
                    }
                    let HirKind::Name(name) =
                        &self.mir.hir[self.child(node, Role::Name)?.index()].kind
                    else {
                        return Err("JS: missing trait member".into());
                    };
                    format!(
                        "{}()[{}]",
                        global_name(symbol, instance),
                        serde_json::to_string(name).unwrap()
                    )
                } else {
                    let receiver = self.sub(node, Role::Receiver)?;
                    let HirKind::Name(name) =
                        &self.mir.hir[self.child(node, Role::Name)?.index()].kind
                    else {
                        return Err("JS: missing member name".into());
                    };
                    format!("({receiver})[{}]", serde_json::to_string(name).unwrap())
                }
            }
            HirKind::TupleProjection(index) => {
                format!("({})[{index}]", self.sub(node, Role::Receiver)?)
            }
            HirKind::Index => format!(
                "index({}, {})",
                self.sub(node, Role::Receiver)?,
                self.sub(node, Role::Index)?
            ),
            HirKind::Match => self.match_expr(node)?,
            HirKind::Closure => {
                let mut params = vec![];
                for edge in &hir.children {
                    if edge.role == Role::Parameter {
                        let symbol = self.mir.hir_symbols[edge.node.index()]
                            .ok_or("JS: missing parameter symbol")?;
                        params.push(format!("v{}", symbol.index()));
                    }
                }
                format!(
                    "(({}) => {})",
                    params.join(","),
                    self.sub(node, Role::Body)?
                )
            }
            HirKind::Call => {
                let callee = self.sub(node, Role::Callee)?;
                let args = hir
                    .children
                    .iter()
                    .filter(|e| e.role == Role::Argument)
                    .map(|e| self.expr(e.node))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("({callee})({})", args.join(","))
            }
            HirKind::Block => {
                let mut body = String::new();
                for edge in &hir.children {
                    if edge.role == Role::Binding {
                        let symbol = self.mir.hir_symbols[edge.node.index()]
                            .ok_or("JS: missing local symbol")?;
                        self.locals.insert(symbol);
                        // Locals are declared lexically, including within nested closures.
                        let value = self.expr(edge.node)?;
                        body.push_str(&format!(
                            "const v{} = {value}; const {} = () => v{};",
                            symbol.index(),
                            global_name(symbol, None),
                            symbol.index()
                        ));
                    }
                }
                format!(
                    "(() => {{{body}return {};}})()",
                    self.sub(node, Role::Result)?
                )
            }
            HirKind::If => format!(
                "({} ? {} : {})",
                self.sub(node, Role::Condition)?,
                self.sub(node, Role::Then)?,
                self.sub(node, Role::Else)?
            ),
            HirKind::Unary(op) => {
                let operand = self.child(node, Role::Operand)?;
                let token = match (op, self.ty(operand)?) {
                    (U::Negate, TypeConstructor::Int | TypeConstructor::Float) => "-",
                    (U::Not | U::LogicalNot, TypeConstructor::Bool) => "!",
                    (U::Not | U::BitNot, TypeConstructor::Int) => "~",
                    _ => return Err("JS prototype: unsupported unary operation".into()),
                };
                let value = format!("({token}{})", self.expr(operand)?);
                if self.ty(node)? == &TypeConstructor::Int {
                    format!("i64({value})")
                } else {
                    value
                }
            }
            HirKind::Binary(op) => {
                let left = self.child(node, Role::Left)?;
                if *op == B::StructUpdate {
                    return Ok(format!(
                        "Object.freeze({{...{}, ...{}}})",
                        self.expr(left)?,
                        self.sub(node, Role::Right)?
                    ));
                }
                if matches!(op, B::Equal | B::NotEqual) {
                    return Ok(format!(
                        "{}equal({}, {})",
                        if *op == B::NotEqual { "!" } else { "" },
                        self.expr(left)?,
                        self.sub(node, Role::Right)?
                    ));
                }
                if !matches!(
                    self.ty(left)?,
                    TypeConstructor::Int
                        | TypeConstructor::Float
                        | TypeConstructor::Bool
                        | TypeConstructor::String
                ) {
                    return Err("JS prototype: only scalar binary operations supported".into());
                }
                let token = match op {
                    B::Add => "+",
                    B::Subtract => "-",
                    B::Multiply => "*",
                    B::Divide => "/",
                    B::Remainder => "%",
                    B::LessThan => "<",
                    B::LessThanOrEqual => "<=",
                    B::GreaterThan => ">",
                    B::GreaterThanOrEqual => ">=",
                    B::Equal => "===",
                    B::NotEqual => "!==",
                    B::And => "&&",
                    B::Or => "||",
                    B::BitAnd => "&",
                    B::BitOr => "|",
                    B::BitXor => "^",
                    _ => return Err("JS prototype: unsupported binary operation".into()),
                };
                let value = format!(
                    "({} {token} {})",
                    self.expr(left)?,
                    self.sub(node, Role::Right)?
                );
                if self.ty(node)? == &TypeConstructor::Int {
                    format!("i64({value})")
                } else {
                    value
                }
            }
            other => return Err(format!("JS prototype: unsupported {other:?} at {node:?}")),
        })
    }
}

impl Emit<'_> {
    fn pattern(&self, node: HirId, value: &str, bindings: &mut String) -> Result<String, String> {
        let hir = &self.mir.hir[node.index()];
        if let Some(selected) = self.mir.member_selections[node.index()] {
            match selected {
                MemberSelection::Boolean(x) => return Ok(format!("{value} === {x}")),
                MemberSelection::EnumVariant { index } => {
                    let mut cond = format!("{value}.tag === {index}");
                    if let Ok(pat) = self.child(node, Role::Pattern) {
                        cond.push_str(&format!(
                            " && ({})",
                            self.pattern(pat, &format!("{value}.value"), bindings)?
                        ));
                    }
                    return Ok(cond);
                }
                MemberSelection::NewtypePattern => {
                    return self.pattern(self.child(node, Role::Pattern)?, value, bindings);
                }
                _ => {}
            }
        }
        match &hir.kind {
            HirKind::Wildcard => Ok("true".into()),
            HirKind::PatternName(_) => {
                let symbol =
                    self.mir.hir_symbols[node.index()].ok_or("JS: missing pattern symbol")?;
                bindings.push_str(&format!("const v{} = {value};", symbol.index()));
                Ok("true".into())
            }
            HirKind::Int(x) => Ok(format!("{value} === {x}n")),
            HirKind::String(x) => Ok(format!("{value} === {}", serde_json::to_string(x).unwrap())),
            HirKind::TuplePattern | HirKind::StructPattern => {
                let mut cond = vec![];
                for (i, edge) in hir
                    .children
                    .iter()
                    .filter(|e| matches!(e.role, Role::Item | Role::Field))
                    .enumerate()
                {
                    let (pat, field) = if edge.role == Role::Item {
                        (edge.node, i.to_string())
                    } else {
                        let HirKind::Name(name) =
                            &self.mir.hir[self.child(edge.node, Role::Name)?.index()].kind
                        else {
                            return Err("JS: missing pattern field".into());
                        };
                        (
                            self.child(edge.node, Role::Pattern)?,
                            serde_json::to_string(name).unwrap(),
                        )
                    };
                    cond.push(self.pattern(pat, &format!("{value}[{field}]"), bindings)?);
                }
                Ok(if cond.is_empty() {
                    "true".into()
                } else {
                    cond.join(" && ")
                })
            }
            other => Err(format!("JS: unsupported pattern {other:?}")),
        }
    }
    fn match_expr(&mut self, node: HirId) -> Result<String, String> {
        let input = self.sub(node, Role::Value)?;
        let mut body = format!("const matched = {input};");
        for edge in self.mir.hir[node.index()]
            .children
            .iter()
            .filter(|e| e.role == Role::Arm)
        {
            let mut bindings = String::new();
            let cond = self.pattern(
                self.child(edge.node, Role::Pattern)?,
                "matched",
                &mut bindings,
            )?;
            let guard = if self.child(edge.node, Role::Guard).is_ok() {
                self.sub(edge.node, Role::Guard)?
            } else {
                "true".into()
            };
            let result = self.sub(edge.node, Role::Value)?;
            body.push_str(&format!(
                "if ({cond}) {{{bindings}if ({guard}) return {result};}}"
            ));
        }
        Ok(format!(
            "(() => {{{body}throw new Error('Telora nonexhaustive match');}})()"
        ))
    }
}
